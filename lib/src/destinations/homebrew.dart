import 'dart:io';

import '../engine/tools.dart';

/// Renders and publishes the formula that points at a release's assets.
///
/// A formula is executable Ruby, so rk emits one fixed structure from
/// validated values and never accepts a template. The formula points at
/// published assets, so it moves only after the release is public — and it is
/// a mutable pointer, so it moves forward under compare-and-swap rather than
/// being overwritten.
class HomebrewFormula {
  /// Builds the formula text.
  ///
  /// Every value is either derived from the manifest or a digest of an asset
  /// rk produced; nothing here is interpolated from configuration.
  static String render({
    required String className,
    required String description,
    required String homepage,
    required String version,
    required String repository,
    required String tag,
    required Map<String, PlatformAsset> assets,
    required String executable,
  }) {
    final buffer = StringBuffer()
      ..writeln('# Generated by rk. Edits are overwritten and will make the')
      ..writeln('# next release stop, because rk compares this file to the')
      ..writeln('# release it names.')
      ..writeln('class $className < Formula')
      ..writeln('  desc "${_escape(description)}"')
      ..writeln('  homepage "${_escape(homepage)}"')
      ..writeln('  version "$version"')
      ..writeln('  license :cannot_represent')
      ..writeln();

    final macArm = assets['macos-arm64'];
    if (macArm != null) {
      buffer
        ..writeln('  on_macos do')
        ..writeln('    on_arm do')
        ..writeln('      url "${_url(repository, tag, macArm.name)}"')
        ..writeln('      sha256 "${macArm.sha256}"')
        ..writeln('    end')
        ..writeln('  end')
        ..writeln();
    }

    final linuxX64 = assets['linux-x64'];
    final linuxArm = assets['linux-arm64'];
    if (linuxX64 != null || linuxArm != null) {
      buffer.writeln('  on_linux do');
      if (linuxX64 != null) {
        buffer
          ..writeln('    on_intel do')
          ..writeln('      url "${_url(repository, tag, linuxX64.name)}"')
          ..writeln('      sha256 "${linuxX64.sha256}"')
          ..writeln('    end');
      }
      if (linuxArm != null) {
        buffer
          ..writeln('    on_arm do')
          ..writeln('      url "${_url(repository, tag, linuxArm.name)}"')
          ..writeln('      sha256 "${linuxArm.sha256}"')
          ..writeln('    end');
      }
      buffer
        ..writeln('  end')
        ..writeln();
    }
    buffer
      ..writeln('  def install')
      ..writeln('    bin.install "$executable"')
      ..writeln('  end')
      ..writeln()
      ..writeln('  test do')
      ..writeln('    assert_match version.to_s, '
          'shell_output("#{bin}/$executable --version")')
      ..writeln('  end')
      ..writeln('end');

    return buffer.toString();
  }

  /// The Homebrew class name for a formula file.
  static String classNameFor(String executable) => executable
      .split(RegExp('[_-]'))
      .where((part) => part.isNotEmpty)
      .map((part) => part[0].toUpperCase() + part.substring(1))
      .join();

  static String _url(String repository, String tag, String asset) =>
      'https://github.com/$repository/releases/download/$tag/$asset';

  /// Values are derived, never interpolated, but a quote would still break the
  /// file — so one cannot appear.
  static String _escape(String value) => value.replaceAll('"', '');
}

class PlatformAsset {
  const PlatformAsset({required this.name, required this.sha256});
  final String name;
  final String sha256;
}

/// Moves a tap's formula forward, only from the state rk inspected.
class HomebrewTap {
  HomebrewTap({
    required this.tools,
    required this.tap,
    required this.checkout,
  });

  final Tools tools;

  /// `owner/homebrew-tap`.
  final String tap;

  /// Where the tap is cloned for this operation.
  final String checkout;

  /// Clones the tap, replaces the formula, and pushes — refusing if the
  /// remote moved under it, which is the compare-and-swap.
  ///
  /// The fresh clone *is* the read: what rk pushes is built on the tap as
  /// it stood moments ago, and a non-fast-forward rejection means it moved
  /// since — re-running clones the moved tap and rebuilds on top of it.
  Future<TapOutcome> update({
    required String formulaPath,
    required String contents,
    required String message,
  }) async {
    // A checkout left by an interrupted run is stale by definition; the
    // compare-and-swap only means anything against a clone made now.
    final stale = Directory(checkout);
    if (stale.existsSync()) stale.deleteSync(recursive: true);

    final cloned = await tools.run('git', [
      'clone',
      '--depth',
      '1',
      'https://github.com/$tap.git',
      checkout,
    ]);
    if (!cloned.ok) return TapOutcome.failed(cloned.summary);

    // Unchanged is decided by bytes, before any git plumbing. The previous
    // version asked `git commit -a` to decide — which never stages a *new*
    // file, so a first-ever formula read as "already current" and nothing
    // was pushed. (It also wrote the file with `cat` and no stdin, so what
    // it committed was empty — [contents] was never used at all. Both are
    // why the tap step's test now asserts the pushed bytes.)
    final file = File('$checkout/$formulaPath');
    final existing = file.existsSync() ? file.readAsStringSync() : null;
    if (existing == contents) return const TapOutcome.unchanged();

    try {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(contents);
    } on FileSystemException catch (error) {
      return TapOutcome.failed('the formula could not be written: $error');
    }

    final added = await tools.run(
      'git',
      ['add', formulaPath],
      workingDirectory: checkout,
    );
    if (!added.ok) return TapOutcome.failed(added.summary);

    final committed = await tools.run(
      'git',
      ['commit', '-m', message],
      workingDirectory: checkout,
    );
    if (!committed.ok) return TapOutcome.failed(committed.summary);

    final pushed = await tools.run(
      'git',
      const ['push'],
      workingDirectory: checkout,
    );
    if (!pushed.ok) {
      return TapOutcome.failed(
        'the tap moved while rk was working — re-running reads it fresh: '
        '${pushed.summary}',
      );
    }
    return const TapOutcome.updated();
  }
}

class TapOutcome {
  const TapOutcome._(this.problem, this.changed);
  const TapOutcome.updated() : this._(null, true);
  const TapOutcome.unchanged() : this._(null, false);
  const TapOutcome.failed(String problem) : this._(problem, false);

  final String? problem;
  final bool changed;
  bool get ok => problem == null;
}
