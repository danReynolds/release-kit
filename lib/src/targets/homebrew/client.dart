/// Renders the formula that installs one of a release's binary archives.
///
/// A formula is executable Ruby, so rk emits one fixed structure from
/// validated release facts and never accepts a template. It points only at
/// immutable GitHub Release assets and moves forward under compare-and-swap.
class HomebrewFormula {
  /// Renders rk's complete formula for one GitHub-hosted release.
  ///
  /// Target adapters supply only release facts. Provider presentation stays
  /// here so staging, validation, and lost-stage recovery cannot drift.
  static String renderRelease({
    required String className,
    required String version,
    required String repository,
    required String tag,
    required Map<String, PlatformAsset> assets,
    required String executable,
  }) =>
      render(
        className: className,
        description: 'Released by rk',
        homepage: 'https://github.com/$repository',
        version: version,
        repository: repository,
        tag: tag,
        assets: assets,
        executable: executable,
      );

  /// Builds the formula text.
  ///
  /// Every value is either derived from the manifest or a digest of an asset
  /// rk produced; nothing here is interpolated from configuration.
  static String render({
    required String className,
    required String description,
    required String homepage,
    required String version,
    required String repository,
    required String tag,
    required Map<String, PlatformAsset> assets,
    required String executable,
  }) {
    if (assets.isEmpty) {
      throw ArgumentError('a Homebrew formula needs at least one archive');
    }
    if (!RegExp(r'^[A-Z][A-Za-z0-9]*$').hasMatch(className)) {
      throw ArgumentError('invalid Homebrew formula class: $className');
    }
    const supportedPlatforms = {
      'macos-arm64',
      'linux-arm64',
      'linux-x64',
    };
    final unsupported = assets.keys.toSet().difference(supportedPlatforms);
    if (unsupported.isNotEmpty) {
      throw ArgumentError(
        'unsupported Homebrew formula platforms: ${unsupported.join(', ')}',
      );
    }
    for (final entry in assets.entries) {
      final expected = '$executable-$version-${entry.key}.tar.gz';
      if (entry.value.name != expected) {
        throw ArgumentError(
          'Homebrew formula archive ${entry.value.name} does not match '
          '$expected',
        );
      }
    }

    final macArm = assets['macos-arm64'];
    final linuxArm = assets['linux-arm64'];
    final linuxX64 = assets['linux-x64'];
    final buffer = StringBuffer()
      ..writeln('# Generated by rk. Edits are overwritten and will make the')
      ..writeln('# next release stop, because rk compares this file to the')
      ..writeln('# release it names.')
      ..writeln('class $className < Formula')
      ..writeln('  desc "${_escape(description)}"')
      ..writeln('  homepage "${_escape(homepage)}"')
      ..writeln('  version "$version"')
      ..writeln();

    if (macArm != null) {
      buffer
        ..writeln('  on_macos do')
        ..writeln('    on_arm do')
        ..writeln('      url "${_url(repository, tag, macArm.name)}"')
        ..writeln('      sha256 "${macArm.sha256}"')
        ..writeln('    end')
        ..writeln('  end')
        ..writeln();
    }

    if (linuxArm != null || linuxX64 != null) {
      buffer.writeln('  on_linux do');
      if (linuxArm != null) {
        buffer
          ..writeln('    on_arm do')
          ..writeln('      url "${_url(repository, tag, linuxArm.name)}"')
          ..writeln('      sha256 "${linuxArm.sha256}"')
          ..writeln('    end');
      }
      if (linuxX64 != null) {
        buffer
          ..writeln('    on_intel do')
          ..writeln('      url "${_url(repository, tag, linuxX64.name)}"')
          ..writeln('      sha256 "${linuxX64.sha256}"')
          ..writeln('    end');
      }
      buffer
        ..writeln('  end')
        ..writeln();
    }

    buffer
      ..writeln('  def install')
      ..writeln('    bin.install "${_escape(executable)}"')
      ..writeln('  end')
      ..writeln()
      ..writeln('  test do')
      ..writeln('    assert_match version.to_s,')
      ..writeln('                 shell_output("#{bin}/'
          '${_escape(executable)} --version")')
      ..writeln('  end')
      ..writeln('end');

    return buffer.toString();
  }

  /// The canonical version claimed by bytes produced by this renderer.
  static Version? versionIn(List<int> bytes) {
    final String source;
    try {
      source = utf8.decode(bytes);
    } on FormatException {
      return null;
    }
    if (!source.startsWith('# Generated by rk.')) return null;
    final matches = RegExp(r'^  version "([^"]+)"$', multiLine: true)
        .allMatches(source)
        .toList();
    if (matches.length != 1) return null;
    final raw = matches.single.group(1)!;
    final parsed = Version.tryParse(raw);
    return parsed != null && parsed.canonical == raw ? parsed : null;
  }

  /// Formulae are Ruby. Keep even future derived metadata inert if it contains
  /// string delimiters or interpolation syntax.
  static String _escape(String value) => value
      .replaceAll('\r', ' ')
      .replaceAll('\n', ' ')
      .replaceAll('\\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll(r'#{', r'\#{');

  static String _url(String repository, String tag, String asset) =>
      'https://github.com/$repository/releases/download/'
      '${Uri.encodeComponent(tag)}/${Uri.encodeComponent(asset)}';
}

class PlatformAsset {
  const PlatformAsset({required this.name, required this.sha256});
  final String name;
  final String sha256;
}

/// The exact public formula base an update was authorized against.
///
/// A missing formula and an existing zero-byte formula are different bases.
/// Existing bytes are represented by their digest so the authority is small
/// while still binding every byte observed by [HomebrewTarget.inspect].
class HomebrewUpdateAuthority {
  const HomebrewUpdateAuthority.absent({this.replacement}) : sha256 = null;

  HomebrewUpdateAuthority.existing(
    List<int> bytes, {
    this.replacement,
  }) : sha256 = Sha256.hex(bytes);

  final String? sha256;

  /// Intended bytes recovered from an authenticated public release when the
  /// local stage is gone. Null for ordinary stage-backed updates.
  final List<int>? replacement;

  /// Binds the public compare-and-swap base and recovered replacement.
  String? get recoveryBinding {
    final bytes = replacement;
    if (bytes == null) return null;
    return '${sha256 ?? 'absent'}:${Sha256.hex(bytes)}';
  }

  bool accepts(List<int>? bytes) {
    final expected = sha256;
    if (expected == null) return bytes == null;
    return bytes != null && Sha256.hex(bytes) == expected;
  }

  String mismatch(List<int>? bytes) {
    final expected = sha256 == null ? 'no formula' : 'sha256 $sha256';
    final actual = bytes == null ? 'no formula' : 'sha256 ${Sha256.hex(bytes)}';
    return 'expected $expected; the fresh tap has $actual';
  }
}

/// Reads one generated tap file exactly as Homebrew users receive it.
///
/// A formula is a mutable channel, not an immutable release artifact. RK
/// advances only a recognizable older generated file and binds that act to
/// the exact
/// bytes read here through [HomebrewUpdateAuthority].
class HomebrewTarget {
  HomebrewTarget({
    required this.tools,
    required this.tap,
    this.workingDirectory,
  });

  final Tools tools;
  final String tap;
  final String? workingDirectory;

  Future<Inspection> inspect({
    required String formulaPath,
    required Version intendedVersion,
    required List<int>? expectedBytes,
    String? expectedSha256,
  }) async {
    if (expectedBytes != null && expectedSha256 != null) {
      throw ArgumentError(
        'Homebrew inspection accepts expected bytes or a digest, not both',
      );
    }
    if (expectedSha256 != null &&
        !RegExp(r'^[0-9a-f]{64}$').hasMatch(expectedSha256)) {
      throw ArgumentError('expected formula digest is not lowercase SHA-256');
    }
    final result = await tools.run(
      'gh',
      ['api', 'repos/$tap/contents/$formulaPath'],
      workingDirectory: workingDirectory,
    );
    if (!result.ok) {
      if (result.summary.contains('(HTTP 404)')) {
        final readable = await tools.run(
          'gh',
          ['repo', 'view', tap, '--json', 'name'],
          workingDirectory: workingDirectory,
        );
        return readable.ok
            ? Inspection.absent(
                detail: 'no formula in the tap yet',
                evidence: const {'public formula': 'absent'},
                authority: HomebrewUpdateAuthority.absent(
                  replacement: expectedBytes,
                ),
              )
            : Inspection.unknown(
                'the tap $tap could not be read, so rk cannot tell what '
                'users install',
              );
      }
      return Inspection.unknown('the tap could not be read: ${result.summary}');
    }

    final List<int> publicBytes;
    try {
      final decoded = jsonDecode(result.stdout);
      final content = decoded is Map ? decoded['content'] : null;
      if (content is! String) {
        return const Inspection.unknown(
          'the tap answered something unreadable',
        );
      }
      publicBytes = base64Decode(content.replaceAll(RegExp(r'\s'), ''));
    } on Object catch (error) {
      return Inspection.unknown(
          'the tap answered something unreadable: $error');
    }

    final publicSha256 = Sha256.hex(publicBytes);
    final version = HomebrewFormula.versionIn(publicBytes);
    return PublicReconciliation.movingChannel(
      label: 'the Homebrew formula',
      intendedVersion: intendedVersion,
      publishedVersion: version,
      payloadMatches:
          (expectedBytes != null && _sameBytes(publicBytes, expectedBytes)) ||
              (expectedSha256 != null && publicSha256 == expectedSha256),
      publishedIdentity: 'sha256:$publicSha256',
      unrecognizedDetail:
          'the Homebrew formula is not a recognizable rk-generated formula',
      advanceAuthority: HomebrewUpdateAuthority.existing(
        publicBytes,
        replacement: expectedBytes,
      ),
    );
  }

  static bool _sameBytes(List<int> a, List<int> b) {
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }
}

/// Moves a tap's formula forward, only from the state rk inspected.
class HomebrewTap {
  HomebrewTap({
    required this.tools,
    required this.tap,
    required this.checkout,
  });

  final Tools tools;

  /// `owner/homebrew-tap`.
  final String tap;

  /// Where the tap is cloned for this operation.
  final String checkout;

  /// Clones the tap, replaces the formula, and pushes — refusing if the
  /// remote moved under it, which is the compare-and-swap.
  ///
  /// The shared target inspection is the authorization read. The fresh clone
  /// must match that exact formula base, and a non-fast-forward rejection then
  /// catches movement after cloning.
  Future<TapOutcome> update({
    required String formulaPath,
    required String contents,
    required String message,
    required HomebrewUpdateAuthority authority,
  }) async {
    // A checkout left by an interrupted run is stale by definition; the
    // compare-and-swap only means anything against a clone made now.
    final stale = Directory(checkout);
    if (stale.existsSync()) stale.deleteSync(recursive: true);

    final cloned = await tools.run('git', [
      'clone',
      '--depth',
      '1',
      'https://github.com/$tap.git',
      checkout,
    ]);
    if (!cloned.ok) {
      return TapOutcome.failed(cloned.summary, transcript: cloned.transcript);
    }

    // The API inspection authorized one exact base. The fresh clone must
    // still contain that base before rk writes anything; the push then guards
    // the remaining clone-to-remote gap with Git's fast-forward rule.
    final file = File('$checkout/$formulaPath');
    final List<int>? existing;
    try {
      existing = file.existsSync() ? file.readAsBytesSync() : null;
    } on FileSystemException catch (error) {
      return TapOutcome.failed('the cloned tap file could not be read: $error');
    }
    if (!authority.accepts(existing)) {
      return TapOutcome.failed(
        'the tap formula changed after rk inspected it; '
        '${authority.mismatch(existing)}. Re-run so rk can inspect the new '
        'public formula before updating it',
      );
    }
    // Unchanged is decided by bytes, before any git plumbing. The previous
    // version asked `git commit -a` to decide — which never stages a *new*
    // file, so a first-ever formula read as "already current" and nothing
    // was pushed. (It also wrote the file with `cat` and no stdin, so what
    // it committed was empty — [contents] was never used at all. Both are
    // why the tap step's test now asserts the pushed bytes.)
    final replacement = utf8.encode(contents);
    if (existing != null && HomebrewTarget._sameBytes(existing, replacement)) {
      return const TapOutcome.unchanged();
    }

    try {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(contents);
    } on FileSystemException catch (error) {
      return TapOutcome.failed('the tap formula could not be written: $error');
    }

    final added = await tools.run(
      'git',
      [
        'add',
        '--',
        formulaPath,
      ],
      workingDirectory: checkout,
    );
    if (!added.ok) {
      return TapOutcome.failed(added.summary, transcript: added.transcript);
    }

    final committed = await tools.run(
      'git',
      ['commit', '-m', message],
      workingDirectory: checkout,
    );
    if (!committed.ok) {
      return TapOutcome.failed(committed.summary,
          transcript: committed.transcript);
    }

    final pushed = await tools.run(
      'git',
      const ['push'],
      workingDirectory: checkout,
    );
    if (!pushed.ok) {
      // Only an actual rejection is the compare-and-swap failing; an auth
      // failure or an unreachable remote wearing "the tap moved" prose
      // would send the operator hunting for a concurrent writer that does
      // not exist.
      final said = pushed.summary.toLowerCase();
      final rejected = said.contains('non-fast-forward') ||
          said.contains('fetch first') ||
          said.contains('rejected');
      return rejected
          ? TapOutcome.failed(
              'the tap moved while rk was working — re-running reads it '
              'fresh: ${pushed.summary}',
              transcript: pushed.transcript,
            )
          : TapOutcome.lostTrack('the push failed: ${pushed.summary}',
              transcript: pushed.transcript);
    }
    return const TapOutcome.updated();
  }
}

class TapOutcome {
  const TapOutcome._(this.problem, this.changed, this.mayHaveActed,
      {this.transcript});
  const TapOutcome.updated() : this._(null, true, true);
  const TapOutcome.unchanged() : this._(null, false, false);
  const TapOutcome.failed(String problem, {String? transcript})
      : this._(problem, false, false, transcript: transcript);
  const TapOutcome.lostTrack(String problem, {String? transcript})
      : this._(problem, false, true, transcript: transcript);

  final String? problem;

  /// What git said when git is what failed — the rest of the account behind
  /// [problem]'s one line.
  final String? transcript;
  final bool changed;
  final bool mayHaveActed;
  bool get ok => problem == null;
}
